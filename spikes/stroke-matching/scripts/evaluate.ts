// Runs the matcher (and Hanzi Writer's matcher) over the fixtures and writes accept/reject rates
// to results/synthetic-results.md. Usage: node scripts/evaluate.ts
import { writeFileSync } from 'node:fs';
import type { Point } from '../src/geometry.ts';
import { toHanziWriterData, toHanziWriterSpace } from '../src/hanziWriterData.ts';
import type { Tolerances } from '../src/matcher.ts';
import { judgeStroke } from '../src/matcher.ts';
import type { Attempt, FixtureFile } from '../src/synth.ts';
import { loadHanziWriterInternals } from './hanziWriterHarness.ts';
import { loadFixtures, loadStrokeData, root, strokePoints } from './common.ts';

const data = loadStrokeData();
const strokes = strokePoints(data);
const fixtures = loadFixtures();
const kindOf = new Map(data.characters.map((c) => [c.char, c.kind]));

type Judge = (fixture: FixtureFile, attempt: Attempt) => boolean;

function pts(a: Attempt, size: number, target: number): Point[] {
  return a.points.map(([x, y]) => ({ x: (x / size) * target, y: (y / size) * target }));
}

function matcherJudge(tol: Tolerances, n = 32): Judge {
  return (f, a) => {
    const size = data.coordinateSize;
    return judgeStroke(
      pts(a, f.canvasSize, size),
      strokes.get(f.char)!,
      a.strokeIndex,
      size,
      tol,
      n,
    ).accepted;
  };
}

const hw = loadHanziWriterInternals();
const hwChars = new Map(
  [...strokes].map(([char, s]) => [
    char,
    hw.parseCharData(char, toHanziWriterData(s, data.coordinateSize)),
  ]),
);
function hanziWriterJudge(leniency: number): Judge {
  return (f, a) => {
    const user = pts(a, f.canvasSize, data.coordinateSize).map((p) =>
      toHanziWriterSpace(p, data.coordinateSize),
    );
    // isOutlineVisible: true is Hanzi Writer's quiz default (showOutline), i.e. trace mode.
    return hw.strokeMatches({ points: user }, hwChars.get(f.char)!, a.strokeIndex, {
      leniency,
      isOutlineVisible: true,
    }).isMatch;
  };
}

interface Rates {
  good: number;
  sloppy: number;
  bad: number;
  borderline: number;
  byVariant: Map<string, number>;
  kanaGood: number;
  kanjiGood: number;
  kanaBad: number;
  kanjiBad: number;
}

function rate(judge: Judge, filter: (f: FixtureFile) => boolean = () => true): Rates {
  const counts = new Map<string, { n: number; acc: number }>();
  const bump = (key: string, accepted: boolean): void => {
    const c = counts.get(key) ?? { n: 0, acc: 0 };
    c.n++;
    if (accepted) c.acc++;
    counts.set(key, c);
  };
  for (const f of fixtures.filter(filter)) {
    const kind = kindOf.get(f.char);
    for (const a of f.attempts) {
      const accepted = judge(f, a);
      bump(a.group, accepted);
      if (a.group !== 'borderline') bump(`${kind}:${a.group === 'bad' ? 'bad' : 'good'}`, accepted);
      if (a.group === 'bad') bump(`v:${a.variant}`, accepted);
    }
  }
  const r = (k: string): number => {
    const c = counts.get(k);
    return c ? c.acc / c.n : NaN;
  };
  const byVariant = new Map<string, number>();
  for (const k of counts.keys()) if (k.startsWith('v:')) byVariant.set(k.slice(2), r(k));
  return {
    good: r('good'),
    sloppy: r('sloppy'),
    bad: r('bad'),
    borderline: r('borderline'),
    byVariant,
    kanaGood: r('kana:good'),
    kanjiGood: r('kanji:good'),
    kanaBad: r('kana:bad'),
    kanjiBad: r('kanji:bad'),
  };
}

const pct = (x: number): string => (Number.isNaN(x) ? 'n/a' : `${(x * 100).toFixed(1)}%`);

const presets: Array<{ name: string; tol: Tolerances }> = [
  { name: 'strict', tol: { startEnd: 0.1, avgDist: 0.07, directionDeg: 30, minLengthRatio: 0.3 } },
  { name: 'medium', tol: { startEnd: 0.15, avgDist: 0.1, directionDeg: 45, minLengthRatio: 0.3 } },
  { name: 'lenient', tol: { startEnd: 0.2, avgDist: 0.13, directionDeg: 60, minLengthRatio: 0.3 } },
  {
    name: 'very lenient',
    tol: { startEnd: 0.25, avgDist: 0.16, directionDeg: 75, minLengthRatio: 0.3 },
  },
];

const counts = { good: 0, sloppy: 0, bad: 0, borderline: 0 };
for (const f of fixtures) for (const a of f.attempts) counts[a.group]++;

const lines: string[] = [];
lines.push('# Synthetic stroke matcher results');
lines.push('');
lines.push(
  `Generated by \`npm run evaluate\` over ${fixtures.length} fixture files: ` +
    `${counts.good} good, ${counts.sloppy} sloppy-but-acceptable, ${counts.bad} bad and ` +
    `${counts.borderline} borderline strokes (gentle sweeps drawn straight or bowed the other way; not counted as errors). ` +
    'Accept rate on good and sloppy strokes should be high (100% minus false rejects); ' +
    'accept rate on bad strokes is the false-accept rate. Tolerances are fractions of canvas size.',
);
lines.push('');

const variants = [...rate(matcherJudge(presets[0]!.tol)).byVariant.keys()].sort();
const header = (first: string): void => {
  lines.push(
    `| ${first} | good accepted | sloppy accepted | bad accepted (false accept) | ${variants.join(' | ')} | borderline accepted |`,
  );
  lines.push(`| --- | --- | --- | --- | ${variants.map(() => '---').join(' | ')} | --- |`);
};
const row = (label: string, r: Rates): void => {
  lines.push(
    `| ${label} | ${pct(r.good)} | ${pct(r.sloppy)} | ${pct(r.bad)} | ${variants
      .map((v) => pct(r.byVariant.get(v) ?? NaN))
      .join(' | ')} | ${pct(r.borderline)} |`,
  );
};

lines.push('## Manabi matcher presets (N = 32)');
lines.push('');
lines.push('Columns after "bad accepted" are the false-accept rate per kind of bad stroke.');
lines.push('');
header('preset (startEnd / avgDist / direction)');
const presetRates = presets.map((p) => ({ p, r: rate(matcherJudge(p.tol)) }));
for (const { p, r } of presetRates) {
  row(`${p.name} (${p.tol.startEnd} / ${p.tol.avgDist} / ${p.tol.directionDeg}°)`, r);
}
lines.push('');

lines.push('## Variant: average distance measured after aligning centroids');
lines.push('');
lines.push(
  'Same presets, but the distance check ignores where the stroke is (start and end checks still do not), so it judges shape only.',
);
lines.push('');
header('preset, centroids aligned');
for (const p of presets) {
  row(
    `${p.name} (${p.tol.startEnd} / ${p.tol.avgDist} / ${p.tol.directionDeg}°)`,
    rate(matcherJudge({ ...p.tol, alignCentroids: true })),
  );
}
lines.push('');

lines.push('## Kana versus kanji (good and sloppy together, then bad)');
lines.push('');
lines.push(
  '| preset | kanji good accepted | kana good accepted | kanji bad accepted | kana bad accepted |',
);
lines.push('| --- | --- | --- | --- | --- |');
for (const { p, r } of presetRates) {
  lines.push(
    `| ${p.name} | ${pct(r.kanjiGood)} | ${pct(r.kanaGood)} | ${pct(r.kanjiBad)} | ${pct(r.kanaBad)} |`,
  );
}
lines.push('');

lines.push('## Sweep: average distance against start/end distance (direction 45°)');
lines.push('');
lines.push('Each cell: good+sloppy accepted / bad accepted.');
lines.push('');
const startEnds = [0.1, 0.15, 0.2, 0.25];
const avgDists = [0.06, 0.08, 0.1, 0.12, 0.15];
lines.push(`| avgDist \\ startEnd | ${startEnds.join(' | ')} |`);
lines.push(`| --- | ${startEnds.map(() => '---').join(' | ')} |`);
for (const ad of avgDists) {
  const cells = startEnds.map((se) => {
    const r = rate(
      matcherJudge({ startEnd: se, avgDist: ad, directionDeg: 45, minLengthRatio: 0.3 }),
    );
    const goodAll =
      (r.good * counts.good + r.sloppy * counts.sloppy) / (counts.good + counts.sloppy);
    return `${pct(goodAll)} / ${pct(r.bad)}`;
  });
  lines.push(`| ${ad} | ${cells.join(' | ')} |`);
}
lines.push('');

lines.push('## Resample count N (medium preset)');
lines.push('');
header('N');
for (const n of [16, 32, 64]) row(String(n), rate(matcherJudge(presets[1]!.tol, n)));
lines.push('');

lines.push(
  '## Hanzi Writer 3.7.3 strokeMatches on the same fixtures (KanjiVG-derived data, outline visible)',
);
lines.push('');
header('leniency');
for (const l of [0.75, 1, 1.5, 2]) row(String(l), rate(hanziWriterJudge(l)));
lines.push('');

const out = lines.join('\n') + '\n';
writeFileSync(new URL('results/synthetic-results.md', root), out);
process.stdout.write(out);
