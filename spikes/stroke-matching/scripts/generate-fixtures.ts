// Writes synthetic good and bad attempts to fixtures/synthetic-<codepoint>.json.
// Usage: node scripts/generate-fixtures.ts
import { writeFileSync } from 'node:fs';
import { generateAttempts } from '../src/synth.ts';
import type { FixtureFile } from '../src/synth.ts';
import { loadStrokeData, root, strokePoints } from './common.ts';

const data = loadStrokeData();
const strokes = strokePoints(data);
let total = 0;
data.characters.forEach((c, idx) => {
  const attempts = generateAttempts(c.char, strokes.get(c.char)!, data.coordinateSize, 1000 + idx);
  total += attempts.length;
  const file: FixtureFile = {
    char: c.char,
    codepoint: c.codepoint,
    canvasSize: data.coordinateSize,
    source: 'synthetic',
    note: 'Generated by scripts/generate-fixtures.ts from KanjiVG strokes (CC BY-SA 3.0). Points are [x, y, t ms] in KanjiVG units (0 to 109).',
    attempts,
  };
  writeFileSync(
    new URL(`fixtures/synthetic-${c.codepoint}.json`, root),
    // One attempt per line keeps diffs readable.
    JSON.stringify({ ...file, attempts: [] }, null, 2).replace(
      '"attempts": []',
      `"attempts": [\n${attempts.map((a) => '    ' + JSON.stringify(a)).join(',\n')}\n  ]`,
    ) + '\n',
  );
});
console.log(`wrote ${total} attempts for ${data.characters.length} characters`);
